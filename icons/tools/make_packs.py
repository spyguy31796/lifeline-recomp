#!/usr/bin/env python3
"""Generate the Xbox / Steam Deck button icon packs (our own art, CC0; no game pixels).

The icons are drawn here from geometry and a 5x7 letter bitmap written for this project. They are PGM files of
palette indices because the target textures are paletted (PSMT8): 0 = transparent, INK = the index the game's own
glyph used, so the game's palette still colours them. Run from icons/:  python3 tools/make_packs.py
"""
import os

# 5x7 capitals (our own bitmaps)
FONT = {
    "A": ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
    "B": ["11110", "10001", "10001", "11110", "10001", "10001", "11110"],
    "X": ["10001", "10001", "01010", "00100", "01010", "10001", "10001"],
    "Y": ["10001", "10001", "01010", "00100", "00100", "00100", "00100"],
}

# Glyphs found on the box (see icons/README.md): texture hash, rect, palette index of the original glyph,
# PS2 button -> the default binding's pad button (input_map.cpp: circle=b, square=x, cross=a, triangle=y).
GLYPHS = [
    # hash               x   y   w   h  ink letter   where
    ("60a3b833bf197925",  7,  5, 23, 22,  9, "B", "Option menu footer: Circle (OK)"),
    ("60a3b833bf197925", 63,  6, 20, 20, 14, "X", "Option menu footer: Square (OK)"),
    ("46c00b69fddee84f",  9,  7, 18, 18, 15, "A", "Option menu footer: Cross (CANCEL)"),
]


def draw(w, h, ink, letter, style):
    px = [[0] * w for _ in range(h)]
    cx, cy = (w - 1) / 2, (h - 1) / 2
    r = min(w, h) / 2 - 0.5
    for y in range(h):
        for x in range(w):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
            if style == "xbox" and r - 2.2 <= d <= r:      # ring
                px[y][x] = ink
            if style == "deck" and d <= r:                 # filled disc
                px[y][x] = ink
    s = 2 if min(w, h) >= 20 else 1                        # letter scale (5x7 cells)
    lw, lh = 5 * s, 7 * s
    ox, oy = (w - lw) // 2, (h - lh) // 2
    for j, row in enumerate(FONT[letter]):
        for i, bit in enumerate(row):
            if bit == "1":
                for dy in range(s):
                    for dx in range(s):
                        px[oy + j * s + dy][ox + i * s + dx] = 0 if style == "deck" else ink
    return px


def write_pgm(path, px):
    h, w = len(px), len(px[0])
    with open(path, "wb") as f:
        f.write(b"P5\n%d %d\n255\n" % (w, h))
        f.write(bytes(v for row in px for v in row))


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for style in ("xbox", "deck"):
        d = os.path.join(here, "packs", style)
        os.makedirs(d, exist_ok=True)
        lines = ["# Lifeline button icon pack: %s (our own art, CC0; generated by tools/make_packs.py)" % style,
                 "# <upload hash> <x> <y> <icon file>   see icons/README.md"]
        for h, x, y, w, hh, ink, letter, where in GLYPHS:
            name = "%s_%dx%d_%d.pgm" % (letter.lower(), w, hh, ink)
            write_pgm(os.path.join(d, name), draw(w, hh, ink, letter, style))
            lines.append("%s %d %d %s   # %s -> %s" % (h, x, y, name, where, letter))
        open(os.path.join(d, "icons.txt"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
